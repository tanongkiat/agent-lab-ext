# ---------------------------------------------------------------- env loading
# replaces: set -a; source .env; set +a
import_dotenv() { # $1 = path (default $LAB_ROOT/.env)
  local path="${1:-$LAB_ROOT/.env}" line name value
  [ -f "$path" ] || return 0
  while IFS= read -r line || [ -n "$line" ]; do
    [[ $line =~ ^[[:space:]]*(export[[:space:]]+)?([A-Za-z_][A-Za-z0-9_]*)[[:space:]]*=(.*)$ ]] || continue
    name="${BASH_REMATCH[2]}"
    value="${BASH_REMATCH[3]}"
    case "$value" in
      \"*\"|\'*\') ;;                       # quoted: keep as is, a # inside is part of the value
      *) value="${value%%[[:space:]]#*}" ;; # otherwise drop a trailing " # comment"
    esac
    value="$(printf '%s' "$value" | sed -E 's/^[[:space:]]+//; s/[[:space:]]+$//')"
    case "$value" in                        # unwrap one layer of quotes, like docker compose env_file
      \"*\") value="${value#\"}"; value="${value%\"}" ;;
      \'*\') value="${value#\'}"; value="${value%\'}" ;;
    esac
    export "$name=$value"
  done < "$path"
}

# .env.bash (generated by tests/bash/env2bash.sh) is preferred: it is plain bash.
# Falls back to parsing .env directly.
load_env() {
  if [ -f "$LAB_ROOT/.env.bash" ]; then
    # shellcheck disable=SC1091
    source "$LAB_ROOT/.env.bash"
  else
    import_dotenv "$LAB_ROOT/.env"
  fi
}
load_env

# write/replace NAME=VALUE in .env (and in .env.bash when it exists) and in the current shell
set_dotenv() { # $1 = name, $2 = value, $3 = path (default $LAB_ROOT/.env)
  local name="$1" value="$2" path="${3:-$LAB_ROOT/.env}" tmp bashfile
  [ -f "$path" ] || : > "$path"
  tmp="$(mktemp)"
  grep -v -E "^(export[[:space:]]+)?${name}=" "$path" > "$tmp" || true
  printf '%s=%s\n' "$name" "$value" >> "$tmp"
  tr -d '\r' < "$tmp" > "$path"
  rm -f "$tmp"
  bashfile="$LAB_ROOT/.env.bash"
  if [ -f "$bashfile" ] && [ "$path" = "$LAB_ROOT/.env" ]; then
    tmp="$(mktemp)"
    grep -v -E "^(export[[:space:]]+)?${name}=" "$bashfile" > "$tmp" || true
    printf 'export %s=%s\n' "$name" "$(printf '%s' "$value" | sed "s/'/'\\\\''/g; s/^/'/; s/\$/'/")" >> "$tmp"
    tr -d '\r' < "$tmp" > "$bashfile"
    rm -f "$tmp"
  fi
  export "$name=$value"
}

