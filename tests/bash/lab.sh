# ------------------------------------------------------------------ helpers
# replaces openssl rand -hex N (same thing here, kept for parity with lab.ps1)
new_rand_hex() { openssl rand -hex "$1"; }

# write a file as UTF-8 without BOM and LF only
write_lf() { # $1 = path, $2 = text
  printf '%s' "$2" | tr -d '\r' > "$1"
}

# curl with the lab-wide options applied (LAB_CURL_OPTS is intentionally unquoted)
lab_curl() { curl $LAB_CURL_OPTS "$@"; }

# POST JSON to LiteLLM (master key by default) -> prints the raw response body
invoke_lab() { # $1 = path, $2 = json body, $3 = key (default master key)
  local p="$1" body="$2" key="${3:-$LITELLM_MASTER_KEY}"
  lab_curl -sS -X POST "$LAB$p" \
    -H "Authorization: Bearer $key" -H "Content-Type: $JSON" -d "$body"
}

# only the HTTP status code (= curl -s -o /dev/null -w "%{http_code}")
# usage: http_code URL [any extra curl args: -X POST -H ... -d ...]
http_code() {
  local err code
  err="$(mktemp)"
  if code="$(lab_curl -sS -o /dev/null -w '%{http_code}' "$@" 2>"$err")"; then
    printf '%s' "$code"
  else
    printf 'ERR: %s' "$(tr '\n' ' ' < "$err" | sed -E 's/[[:space:]]+$//')"
  fi
  rm -f "$err"
}

# = code() in the original: status code of a chat completion through litellm-proxy
test_chat_code() { # $1 = key, $2 = model, $3 = user (optional)
  local key="$1" model="$2" user="${3:-}" body
  body="$(jq -nc --arg m "$model" --arg u "$user" \
    '{model:$m, user:$u, messages:[{role:"user",content:"hi"}]}')"
  http_code "$LAB/v1/chat/completions" -X POST \
    -H "Authorization: Bearer $key" -H "Content-Type: $JSON" -d "$body"
}

# send one message, print the response object
invoke_chat() { # $1 = uri, $2 = bearer, $3 = model, $4 = content
  local body
  body="$(jq -nc --arg m "$3" --arg c "$4" \
    '{model:$m, messages:[{role:"user",content:$c}]}')"
  lab_curl -sS -X POST "$1" -H "Authorization: Bearer $2" -H "Content-Type: $JSON" -d "$body"
}

# = token() in the original: access token from Keycloak (password grant)
get_lab_token() { # $1 = username (password = username)
  lab_curl -sS -X POST "$IDP_URL/realms/$IDP_REALM/protocol/openid-connect/token" \
    -d grant_type=password -d client_id=lab-app \
    --data-urlencode "username=$1" --data-urlencode "password=$1" | jq -r '.access_token'
}

# = $KC in the original: kcadm inside the idp container (stdin works: ... | kc update ... -f -)
kc() { docker compose exec -T idp /opt/keycloak/bin/kcadm.sh "$@"; }

# = W in the original: send a billing webhook to subscription-service (Step 8)
send_billing() { # $1 = json event
  lab_curl -sS -X POST "$BILLING_URL/webhook/billing" \
    -H "Content-Type: $JSON" -H "x-webhook-secret: $WEBHOOK_SECRET" -d "$1"
}

# print model_list entries for every OPENAI_COMPATIBLE_<n>_* in .env (compat-1, compat-2, ...)
# -> paste into litellm/config.yaml
get_compat_yaml() {
  local n m
  for n in $(env | sed -nE 's/^OPENAI_COMPATIBLE_([0-9]+)_BASE_URL=.*/\1/p' | sort -n); do
    eval "m=\${OPENAI_COMPATIBLE_${n}_MODEL}"
    printf '  - model_name: compat-%s\n' "$n"
    printf '    litellm_params:\n'
    printf '      model: openai/%s\n' "$m"
    printf '      api_base: os.environ/OPENAI_COMPATIBLE_%s_BASE_URL\n' "$n"
    printf '      api_key: os.environ/OPENAI_COMPATIBLE_%s_API_KEY\n' "$n"
    printf '    model_info:\n'
    printf '      access_groups: [tier-basic, tier-pro]\n'
  done
}

